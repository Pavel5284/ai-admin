/**
 * Светские реплики: приветствие, благодарность, «как дела», вопрос «ты бот?»,
 * волнение, прощание. Это отдельный слой, а не интент записи: он не получает
 * права создавать, переносить или отменять запись.
 *
 * Детектор намеренно чистый и работает по словам/фразам, без LLM. Границы
 * слов считает `wb`, потому что `\b` и `\w` в JS не дружат с кириллицей.
 */

import { wb } from './normalize';

export type SmalltalkKind =
  | 'greeting'
  | 'thanks'
  | 'how_are_you'
  | 'bot'
  | 'worry'
  | 'positive'
  | 'goodbye'
  | 'apology'
  | 'ack';

const atEnd = (text: string, phrase: string): boolean =>
  new RegExp(String.raw`(?:^|\s)(?:${phrase})\s*[.!?…]*\s*$`, 'iu').test(text);

const PATTERNS: Array<[SmalltalkKind, RegExp]> = [
  // Прощание проверяем раньше благодарности: «спасибо, до свидания» — это прощание.
  ['goodbye', wb('до\\s+свидания|до\\s+встречи|до\\s+связи|всего\\s+доброго|всего\\s+хорошего|увидимся|бай')],
  ['thanks', wb('спасибо|благодарю|спс|thanks|thank\\s+you')],
  // «как вы» — только если фраза закончилась: «как вы работаете?» — это FAQ.
  ['how_are_you', wb('как\\s+дела|как\\s+настроение|как\\s+жизнь|как\\s+сам|как\\s+сами|что\\s+нового')],
  ['bot', wb('ты\\s+бот|вы\\s+бот|ты\\s+робот|вы\\s+робот|ты\\s+человек|вы\\s+человек|кто\\s+вы|кто\\s+ты|с\\s+кем\\s+говорю|ты\\s+настоящий|вы\\s+настоящий|живой\\s+человек')],
  ['worry', wb('волнуюсь|переживаю|нервничаю|боюсь|страшно|тревожно|мандражирую')],
  ['positive', wb('супер|класс|отлично|здорово|круто|молодцы|молодец|нравится|доволен|довольна|прекрасно|замечательно|приятно')],
  ['greeting', wb('привет|здравствуйте|здравствуй|здрасьте|хай|hello|hi|добрый\\s+день|доброе\\s+утро|добрый\\s+вечер|доброго\\s+дня')],
  ['apology', wb('извините|извиняюсь|простите|сорри|сори')],
  ['ack', wb('понятно|ясно|ладно|принято|понял|поняла')],
];

/** «Пока» в конце — прощание, «пока не знаю» — нет. */
const goodbyeAtEnd = (text: string): boolean => atEnd(text, 'пока');

/** «Как вы?» — только целиком; «как вы работаете?» не перехватываем. */
const howAreYouAtEnd = (text: string): boolean => atEnd(text, 'как\\s+вы');

/**
 * Вернуть тип светской реплики или null. Функция не решает, отвечать ли:
 * это делает автомат, который знает состояние и уже найденные слоты.
 */
export function detectSmalltalk(text: string): SmalltalkKind | null {
  const t = text.trim();
  if (!t) return null;

  // Отрицание не должно превращаться в комплимент: «мне не нравится».
  const negatedPositive = /(?:^|\s)не\s+(?:нравится|супер|класс|отлично|здорово|круто|приятно)/iu.test(t);

  if (goodbyeAtEnd(t)) return 'goodbye';
  if (howAreYouAtEnd(t)) return 'how_are_you';

  for (const [kind, re] of PATTERNS) {
    if (kind === 'positive' && negatedPositive) continue;
    if (re.test(t)) return kind;
  }
  return null;
}
