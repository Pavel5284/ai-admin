import { it, expect, describe } from 'vitest';
import { parsePhone, toE164 } from '../src/phone';

describe('parsePhone', () => {
  it.each([
    // примеры из гайда
    ['восемь девятьсот шестнадцать двести тридцать четыре пятьдесят шесть семьдесят восемь', '+79162345678'],
    ['плюс семь девять один шесть два три четыре пять шесть семь восемь', '+79162345678'],
    ['девятьсот шестнадцать двести тридцать четыре пять шесть семь восемь', '+79162345678'],
    ['8 (916) 234-56-78', '+79162345678'],
    // обычные формы
    ['+79161234567', '+79161234567'],
    ['89162345678', '+79162345678'],
    ['9162345678', '+79162345678'],
    ['мой номер 89162345678', '+79162345678'],
    ['89162345678 пожалуйста', '+79162345678'],
    ['в 18:00 звоните 89162345678', '+79162345678'],
    ['916.234.56.78', '+79162345678'],
    ['восемь девятьсот шестнадцать два три четыре пять шесть семь восемь', '+79162345678'],
    ['+7 916 234 56 78', '+79162345678'],
    ['(916) 234-56-78', '+79162345678'],
    // «номер» + номер словами: часы из начала реплики не должны попасть в телефон
    ['в шесть вечера, номер восемь девятьсот шестнадцать двести тридцать четыре пятьдесят шесть семьдесят восемь', '+79162345678'],
  ])('%s → %s', (input, phone) => {
    expect(parsePhone(input)).toEqual({ status: 'ok', phone });
  });

  it('возвращает неполный номер, но не копит его между репликами', () => {
    expect(parsePhone('8')).toEqual({ status: 'partial', digits: '8' });
    expect(parsePhone('8916')).toEqual({ status: 'partial', digits: '8916' });
    expect(parsePhone('восемь девятьсот')).toEqual({ status: 'partial', digits: '8900' });
    // Хвост прошлого номера не должен склеиваться с новым вводом.
    expect(parsePhone('234 56 78')).toEqual({ status: 'partial', digits: '2345678' });
  });

  it('просит повторить слишком длинный номер', () => {
    expect(parsePhone('8 916 234 56 78 9')).toEqual({ status: 'too_long', digits: '891623456789' });
  });

  it('не считает номером 11 цифр не того формата', () => {
    expect(parsePhone('12345678901').status).toBe('too_long');
  });

  it('не путает время и дату с номером', () => {
    expect(parsePhone('в 18:00').status).toBe('none');
    expect(parsePhone('23.10').status).toBe('none');
  });

  it('понимает «два нуля»', () => {
    expect(parsePhone('плюс семь девятьсот шестнадцать два нуля четыре пять шесть семь восемь'))
      .toEqual({ status: 'ok', phone: '+79160045678' });
  });
});

describe('toE164', () => {
  it('приводит к единому формату', () => {
    expect(toE164('89162345678')).toBe('+79162345678');
    expect(toE164('79162345678')).toBe('+79162345678');
    expect(toE164('9162345678')).toBe('+79162345678');
    expect(toE164('123')).toBeNull();
  });
});
