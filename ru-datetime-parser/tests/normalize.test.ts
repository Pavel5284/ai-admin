import { it, expect, describe } from 'vitest';
import { normalize, wb } from '../src/normalize';

describe('normalize', () => {
  it.each([
    // регистр и буква ё
    ['ПРИВЕТ', 'привет'],
    ['ёжик', 'ежик'],
    // пунктуация и пробелы
    ['Запишите меня!', 'запишите меня'],
    ['  лишние   пробелы  ', 'лишние пробелы'],
    ['на стрижку, пожалуйста', 'на стрижку пожалуйста'],
    // слова-паразиты
    ['ну эээ запишите меня', 'запишите меня'],
    ['короче, стрижка', 'стрижка'],
    ['значит, борода', 'борода'],
    ['вот тебе и типичный пример', 'тебе и типичный пример'],
    ['как бы стрижка', 'стрижка'],
    // ошибки распознавания
    ['назавтра', 'на завтра'],
    ['во скок', 'во сколько'],
    ['мужскуюстрижку', 'мужскую стрижку'],
    ['двеси тридцать четыре', '234'],
    // числительные
    ['в шесть вечера', 'в 6 вечера'],
    ['двадцать три', '23'],
    ['на двадцать третьего', 'на 23'],
    // двоеточие и дефис должны уцелеть
    ['в 18:00', 'в 18:00'],
    ['23-го', '23'],
  ])('%s → %s', (input, expected) => {
    expect(normalize(input)).toBe(expected);
  });

  it('переводит номер, продиктованный словами', () => {
    expect(
      normalize('восемь девятьсот шестнадцать двести тридцать четыре пятьдесят шесть семьдесят восемь'),
    ).toBe('8 916 234 56 78');
  });

  it('не теряет служебные слова', () => {
    expect(normalize('без пятнадцати шесть')).toBe('без 15 6');
  });
});

describe('wb', () => {
  it('учитывает кириллицу', () => {
    expect(wb('завтра').test('на завтра в шесть')).toBe(true);
    expect(wb('завтра').test('назавтра')).toBe(false);
  });
});
