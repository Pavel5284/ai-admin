import { it, expect, describe } from 'vitest';
import { findNumbers, wordsToDigits } from '../../src/nlu/numbers';

describe('wordsToDigits', () => {
  it.each([
    // количественные
    ['ноль', '0'],
    ['пять', '5'],
    ['десять', '10'],
    ['одиннадцать', '11'],
    ['девятнадцать', '19'],
    ['двадцать', '20'],
    ['тридцать', '30'],
    ['сорок', '40'],
    ['пятьдесят', '50'],
    ['шестьдесят', '60'],
    ['семьдесят', '70'],
    ['восемьдесят', '80'],
    ['девяносто', '90'],
    ['сто', '100'],
    ['двести', '200'],
    ['девятьсот', '900'],
    ['тысяча', '1000'],
    // падежные формы
    ['одна', '1'],
    ['две', '2'],
    ['трёх', '3'],
    ['четыре', '4'],
    ['пяти', '5'],
    ['шести', '6'],
    ['семи', '7'],
    ['восьми', '8'],
    ['девяти', '9'],
    ['десяти', '10'],
    ['пятнадцати', '15'],
    ['двадцати', '20'],
    ['тридцати', '30'],
    // порядковые
    ['первый', '1'],
    ['второе', '2'],
    ['третьего', '3'],
    ['четвертого', '4'],
    ['пятого', '5'],
    ['шестого', '6'],
    ['седьмого', '7'],
    ['восьмого', '8'],
    ['девятого', '9'],
    ['десятого', '10'],
    // составные и группировка
    ['двадцать три', '23'],
    ['пятнадцать тридцать', '15 30'],
    ['двадцать третьего', '23'],
    ['сто пятьдесят', '150'],
    ['без пятнадцати шесть', 'без 15 6'],
    ['девятьсот шестнадцать', '916'],
    ['двести тридцать четыре', '234'],
    ['девятьсот шестнадцать двести тридцать четыре', '916 234'],
    ['девять один шесть', '9 1 6'],
    ['тридцать первое', '31'],
    // цифры, которые распознавание уже выдало
    ['в 15 30', 'в 15 30'],
    ['23-го', '23'],
    ['056', '056'],
    ['телефон 89162345678', 'телефон 89162345678'],
    // длинный номер словами
    [
      'восемь девятьсот шестнадцать двести тридцать четыре пятьдесят шесть семьдесят восемь',
      '8 916 234 56 78',
    ],
  ])('%s → %s', (input, expected) => {
    expect(wordsToDigits(input)).toBe(expected);
  });

  it('не трогает слова, которые не числа', () => {
    expect(wordsToDigits('хочу стрижку и бороду')).toBe('хочу стрижку и бороду');
  });
});

describe('findNumbers', () => {
  it('находит числа с их границами', () => {
    const tokens = findNumbers('в 18:00');
    expect(tokens.map((t) => t.value)).toEqual([18, 0]);
    expect(tokens[0]).toMatchObject({ value: 18, raw: '18', start: 2, end: 4 });
  });

  it('группирует по разрядам', () => {
    expect(findNumbers('девятьсот шестнадцать').map((t) => t.value)).toEqual([916]);
    expect(findNumbers('без пятнадцати шесть').map((t) => t.value)).toEqual([15, 6]);
    expect(findNumbers('девять один шесть').map((t) => t.value)).toEqual([9, 1, 6]);
  });

  it('помечает порядковые', () => {
    expect(findNumbers('двадцать третьего')[0]).toMatchObject({ value: 23, ordinal: true });
    expect(findNumbers('23-го')[0]).toMatchObject({ value: 23, raw: '23', ordinal: true });
    expect(findNumbers('двадцать три')[0]).toMatchObject({ value: 23, ordinal: false });
  });

  it('хранит исходные цифры, чтобы не потерять ведущий ноль', () => {
    expect(findNumbers('056')[0]).toMatchObject({ value: 56, raw: '056' });
  });
});
