import { it, expect, describe } from 'vitest';
import { parseWhen } from '../src/dates';
import { normalize } from '../src/normalize';

const NOW = new Date(2026, 9, 15, 12, 0);   // четверг, 15 октября 2026 (месяц с нуля!)

const when = (text: string) => parseWhen(normalize(text), NOW);

describe('parseWhen', () => {
  it.each([
    ['завтра в шесть вечера', { date: '2026-10-16', time: '18:00' }],
    ['послезавтра после обеда', { date: '2026-10-17', timeRange: { from: '13:00', to: '17:00' } }],
    ['после завтра после обеда', { date: '2026-10-17', timeRange: { from: '13:00', to: '17:00' } }],
    ['давай на после завтра после обеда', { date: '2026-10-17', timeRange: { from: '13:00', to: '17:00' } }],
    ['двадцать третьего в пятнадцать тридцать', { date: '2026-10-23', time: '15:30' }],
    ['в субботу в половине пятого', { date: '2026-10-17', time: '16:30' }],
    ['через три дня без пятнадцати шесть', { date: '2026-10-18', time: '17:45' }],

    // относительные дни
    ['сегодня', { date: '2026-10-15' }],
    ['через неделю', { date: '2026-10-22' }],
    ['через две недели', { date: '2026-10-29' }],
    // даты цифрами
    ['23.10', { date: '2026-10-23' }],
    ['23.10.2027', { date: '2027-10-23' }],
    ['23 числа', { date: '2026-10-23' }],
    ['23 октября', { date: '2026-10-23' }],
    ['шестнадцатое октября', { date: '2026-10-16' }],
    ['пятнадцатого октября', { date: '2026-10-15' }],
    // дни недели
    ['в среду', { date: '2026-10-21' }],
    ['в пятницу', { date: '2026-10-16' }],
    ['в следующий вторник', { date: '2026-10-20' }],
    ['на выходных', { date: '2026-10-17' }],
    // время
    ['в 15:30', { time: '15:30' }],
    ['в 18:00', { time: '18:00' }],
    ['в 5 вечера', { time: '17:00' }],
    ['в 5', { time: '17:00' }],
    ['в 10', { time: '10:00' }],
    ['в 6 утра', { time: '06:00' }],
    ['в полдень', { time: '12:00' }],
    ['в четверть 7', { time: '18:15' }],
    ['после обеда', { timeRange: { from: '13:00', to: '17:00' } }],
    ['утром', { timeRange: { from: '10:00', to: '12:00' } }],
    ['вечером', { timeRange: { from: '17:00', to: '21:00' } }],
  ])('%s', (text, expected) => {
    expect(when(text)).toMatchObject(expected);
  });

  it('не путает дату и время', () => {
    expect(when('в 15 30').date).toBeUndefined();
    expect(when('23 в 15 30')).toMatchObject({ date: '2026-10-23', time: '15:30' });
  });

  it('просит уточнить день, если сказано «на следующей неделе»', () => {
    expect(when('на следующей неделе').ambiguous).toContain('date');
  });

  it.each([
    // относительные дни
    ['сегодня', { date: '2026-10-15' }],
    ['завтра', { date: '2026-10-16' }],
    ['послезавтра', { date: '2026-10-17' }],
    ['через 3 дня', { date: '2026-10-18' }],
    ['через 10 дней', { date: '2026-10-25' }],
    ['через неделю', { date: '2026-10-22' }],
    ['через две недели', { date: '2026-10-29' }],
    ['через месяц', { date: '2026-11-14' }],
    // день месяца
    ['23 числа', { date: '2026-10-23' }],
    ['31 числа', { date: '2026-10-31' }],
    ['1 числа', { date: '2026-11-01' }],
    ['23 октября', { date: '2026-10-23' }],
    ['30 октября', { date: '2026-10-30' }],
    ['12 ноября', { date: '2026-11-12' }],
    ['25 декабря', { date: '2026-12-25' }],
    ['23 января', { date: '2027-01-23' }],
    ['5 февраля', { date: '2027-02-05' }],
    ['10 марта', { date: '2027-03-10' }],
    ['2 апреля', { date: '2027-04-02' }],
    ['1 мая', { date: '2027-05-01' }],
    ['7 июня', { date: '2027-06-07' }],
    ['4 июля', { date: '2027-07-04' }],
    ['8 августа', { date: '2027-08-08' }],
    ['9 сентября', { date: '2027-09-09' }],
    // даты цифрами
    ['23.10', { date: '2026-10-23' }],
    ['05.11', { date: '2026-11-05' }],
    ['01.10', { date: '2027-10-01' }],
    ['23.10.2026', { date: '2026-10-23' }],
    ['01.01.2027', { date: '2027-01-01' }],
    // дни недели
    ['в понедельник', { date: '2026-10-19' }],
    ['в вторник', { date: '2026-10-20' }],
    ['в среду', { date: '2026-10-21' }],
    ['в четверг', { date: '2026-10-15' }],
    ['в пятницу', { date: '2026-10-16' }],
    ['в субботу', { date: '2026-10-17' }],
    ['в воскресенье', { date: '2026-10-18' }],
    ['в ближайшую пятницу', { date: '2026-10-16' }],
    ['в следующий вторник', { date: '2026-10-20' }],
    ['на выходные', { date: '2026-10-17' }],
    // время точное
    ['в 9:45', { time: '09:45' }],
    ['в 15 30', { time: '15:30' }],
    ['в 10', { time: '10:00' }],
    ['в 5', { time: '17:00' }],
    ['в 21', { time: '21:00' }],
    ['в 3 часа дня', { time: '15:00' }],
    ['в 6 вечера', { time: '18:00' }],
    ['в 7 утра', { time: '07:00' }],
    ['в 12 ночи', { time: '00:00' }],
    ['в полдень', { time: '12:00' }],
    ['в половине 5', { time: '16:30' }],
    ['в четверть 7', { time: '18:15' }],
    ['без 15 6', { time: '17:45' }],
    // время неточное
    ['утром', { timeRange: { from: '10:00', to: '12:00' } }],
    ['после обеда', { timeRange: { from: '13:00', to: '17:00' } }],
    ['днем', { timeRange: { from: '13:00', to: '17:00' } }],
    ['вечером', { timeRange: { from: '17:00', to: '21:00' } }],
    ['ближе к вечеру', { timeRange: { from: '17:00', to: '21:00' } }],
    // дата и время вместе
    ['завтра в 18:00', { date: '2026-10-16', time: '18:00' }],
    ['20 октября в 15:00', { date: '2026-10-20', time: '15:00' }],
    ['в субботу утром', { date: '2026-10-17', timeRange: { from: '10:00', to: '12:00' } }],
    ['послезавтра в 10:30', { date: '2026-10-17', time: '10:30' }],
  ])('%s', (text, expected) => {
    expect(when(text)).toMatchObject(expected);
  });

  it('не выдумывает дату, если её не сказали', () => {
    expect(when('стрижка').date).toBeUndefined();
    expect(when('в 18:00').date).toBeUndefined();
    expect(when('в 15 30').date).toBeUndefined();
  });

  it('берёт последнее значение, если клиент поправил себя', () => {
    // NOW — четверг 15 октября, поэтому «в субботу» это 17-е, а не сегодня.
    expect(when('завтра, нет, в субботу')).toMatchObject({ date: '2026-10-17' });
    expect(when('в 18:00, нет, в 12:00')).toMatchObject({ time: '12:00' });
  });

  it('часы 10–21 не бывают неоднозначными', () => {
    expect(when('в 10').ambiguous).toBeUndefined();
    expect(when('в 5').ambiguous).toBeUndefined();
  });
});
