export const variant = (list: string[], n: number) => list[n % list.length];

/** Русские числительные: 1 цифра, 2 цифры, 5 цифр. */
const plural = (n: number, one: string, few: string, many: string): string => {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return one;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return few;
  return many;
};

